-- ###############################################

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;

-- Layer contents
SELECT * FROM DEA_BATCH_SCD2.RAW.PRODUCT_CP;
SELECT * FROM DEA_BATCH_SCD2.RAW.PRODUCT_RAW ORDER BY PRODUCT_ID;
SELECT * FROM DEA_BATCH_SCD2.TRANSFORMED.PRODUCT_TRANSFORMED ORDER BY PRODUCT_ID, UPDATE_DTS DESC;
SELECT * FROM DEA_BATCH_SCD2.SNAPSHOT.PRODUCT_SNAPSHOT ORDER BY PRODUCT_ID, DBT_VALID_TO DESC;

-- Row counts per layer
SELECT 'PRODUCT_CP' AS tbl, COUNT(*) FROM DEA_BATCH_SCD2.RAW.PRODUCT_CP
UNION ALL SELECT 'PRODUCT_RAW', COUNT(*) FROM DEA_BATCH_SCD2.RAW.PRODUCT_RAW
UNION ALL SELECT 'PRODUCT_TRANSFORMED', COUNT(*) FROM DEA_BATCH_SCD2.TRANSFORMED.PRODUCT_TRANSFORMED
UNION ALL SELECT 'PRODUCT_SNAPSHOT', COUNT(*) FROM DEA_BATCH_SCD2.SNAPSHOT.PRODUCT_SNAPSHOT;

-- Full history for one product
SELECT * FROM DEA_BATCH_SCD2.SNAPSHOT.PRODUCT_SNAPSHOT
WHERE PRODUCT_ID = 3001
ORDER BY DBT_VALID_FROM;

-- Current version only
SELECT * FROM DEA_BATCH_SCD2.SNAPSHOT.PRODUCT_SNAPSHOT
WHERE PRODUCT_ID = 3001 AND DBT_VALID_TO IS NULL;

-- Closed vs current versions
SELECT
  COUNT_IF(DBT_VALID_TO IS NOT NULL) AS closed_versions,
  COUNT_IF(DBT_VALID_TO IS NULL)     AS current_versions
FROM DEA_BATCH_SCD2.SNAPSHOT.PRODUCT_SNAPSHOT;

-- Bad records must not reach any layer (expect 0 rows)
SELECT 'RAW' AS layer, PRODUCT_ID FROM DEA_BATCH_SCD2.RAW.PRODUCT_RAW WHERE PRODUCT_ID IN (4001, 4003, 4007)
UNION ALL
SELECT 'TRANSFORMED', PRODUCT_ID FROM DEA_BATCH_SCD2.TRANSFORMED.PRODUCT_TRANSFORMED WHERE PRODUCT_ID IN (4001, 4003, 4007)
UNION ALL
SELECT 'SNAPSHOT', PRODUCT_ID FROM DEA_BATCH_SCD2.SNAPSHOT.PRODUCT_SNAPSHOT WHERE PRODUCT_ID IN (4001, 4003, 4007);

-- Point-in-time: catalog as it looked just after the first load
SET as_of = (SELECT MIN(DBT_VALID_FROM) + INTERVAL '1 second'
             FROM DEA_BATCH_SCD2.SNAPSHOT.PRODUCT_SNAPSHOT);

SELECT PRODUCT_ID, PRODUCT_NAME, PRODUCT_PRICE, PRODUCT_SUPPLIER_NAME
FROM DEA_BATCH_SCD2.SNAPSHOT.PRODUCT_SNAPSHOT
WHERE DBT_VALID_FROM <= $as_of
  AND (DBT_VALID_TO > $as_of OR DBT_VALID_TO IS NULL)
ORDER BY PRODUCT_ID;
